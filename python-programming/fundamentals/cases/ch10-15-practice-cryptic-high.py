def f(p):
    q = [float(x.split("|")[3]) for x in p]
    return max(q), min(q)


n = [
    "NM|2025-11-01|2.6|7.6|0.0|구름많음",
    "NM|2025-11-02|1.6|10.8|0.0|흐림",
    "NM|2025-11-03|2.4|7.4|0.0|흐림",
    "NM|2025-11-04|3.7|9.8|8.5|비",
    "NM|2025-11-05|3.3|12.0|1.0|비",
]
a, b = f(n)
print(a, b)
