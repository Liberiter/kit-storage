CREATE TABLE book_price_changes (
    change_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id integer NOT NULL REFERENCES books (book_id),
    old_price integer NOT NULL,
    new_price integer NOT NULL,
    changed_at timestamp with time zone NOT NULL
);

CREATE FUNCTION log_book_price_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO book_price_changes (book_id, old_price, new_price, changed_at)
    VALUES (OLD.book_id, OLD.price, NEW.price, now());
    RETURN NULL;
END;
$$;

CREATE TRIGGER books_price_history
AFTER UPDATE OF price ON books
FOR EACH ROW
EXECUTE FUNCTION log_book_price_change();

UPDATE books SET price = price WHERE book_id = 3;

SELECT change_id, book_id, old_price, new_price FROM book_price_changes;
