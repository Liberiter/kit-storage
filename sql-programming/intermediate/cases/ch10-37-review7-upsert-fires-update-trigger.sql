CREATE TABLE supply_price_changes (
    change_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id integer NOT NULL REFERENCES books (book_id),
    old_price integer NOT NULL,
    new_price integer NOT NULL,
    changed_at timestamp with time zone NOT NULL
);

CREATE FUNCTION log_supply_price_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO supply_price_changes (book_id, old_price, new_price, changed_at)
    VALUES (OLD.book_id, OLD.supplier_price, NEW.supplier_price, now());
    RETURN NULL;
END;
$$;

CREATE TRIGGER book_supply_price_history
AFTER UPDATE OF supplier_price ON book_supply
FOR EACH ROW
EXECUTE FUNCTION log_supply_price_change();

WITH clean AS (
    SELECT
        book_id,
        supplier_price,
        supplier_stock,
        received_at,
        row_number() OVER (
            PARTITION BY book_id
            ORDER BY feed_date DESC, feed_id DESC
        ) AS 최신순
    FROM supplier_feed
    WHERE supplier_price > 0
        AND EXISTS (
            SELECT 1 FROM books WHERE books.book_id = supplier_feed.book_id
        )
)
INSERT INTO book_supply (book_id, supplier_price, supplier_stock, updated_at)
SELECT book_id, supplier_price, supplier_stock, received_at
FROM clean
WHERE 최신순 = 1
ON CONFLICT (book_id) DO UPDATE
SET supplier_price = EXCLUDED.supplier_price,
    supplier_stock = EXCLUDED.supplier_stock,
    updated_at = EXCLUDED.updated_at;

SELECT
    count(*) AS 이력줄수,
    count(*) FILTER (WHERE old_price <> new_price) AS 값이바뀐줄
FROM supply_price_changes;
