CREATE TABLE review_edits (
    edit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id integer NOT NULL REFERENCES reviews (review_id),
    old_rating integer NOT NULL,
    old_comment text,
    old_review_date date NOT NULL,
    edited_at timestamp with time zone NOT NULL
);

CREATE FUNCTION log_review_edit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO review_edits (
        review_id, old_rating, old_comment, old_review_date, edited_at
    )
    VALUES (OLD.review_id, OLD.rating, OLD.comment, OLD.review_date, now());
    RETURN NULL;
END;
$$;

CREATE TRIGGER reviews_edit_history
AFTER UPDATE ON reviews
FOR EACH ROW
EXECUTE FUNCTION log_review_edit();

