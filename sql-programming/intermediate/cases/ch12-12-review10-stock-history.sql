CREATE TABLE book_stock_changes (
    change_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id integer NOT NULL REFERENCES books (book_id),
    old_stock integer NOT NULL,
    new_stock integer NOT NULL,
    changed_at timestamp with time zone NOT NULL
);

CREATE FUNCTION log_book_stock_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO book_stock_changes (book_id, old_stock, new_stock, changed_at)
    VALUES (OLD.book_id, OLD.stock, NEW.stock, now());
    RETURN NULL;
END;
$$;

CREATE TRIGGER books_stock_history
AFTER UPDATE OF stock ON books
FOR EACH ROW
EXECUTE FUNCTION log_book_stock_change();
