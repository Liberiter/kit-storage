-- 9장 주장 케이스 (정수, 세션 시간대를 서울로 둔 세션) — 본문에 코드 블록으로 등장하지 않는다.
-- 뒷받침하는 자리: 9.1 «흔한 실수» 2의 「세션을 서울로 바꿔 둔 사람이 돌리면 1797이 나옵니다」
-- (오프셋 없이 적은 범위가 세션 시간대로 읽힌다 — ch09-10 과 같은 WHERE, 세션만 다르다)
SET timezone TO 'Asia/Seoul';
SELECT '세션이 서울일 때 오프셋 없이 센 6월 1일' AS 주장, count(*) AS 실측값
FROM page_views
WHERE viewed_at >= '2026-06-01' AND viewed_at < '2026-06-02';
