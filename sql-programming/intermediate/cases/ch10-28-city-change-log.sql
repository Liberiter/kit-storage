CREATE TABLE customer_city_changes (
    change_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers (customer_id),
    old_city text NOT NULL,
    new_city text NOT NULL,
    changed_at timestamp with time zone NOT NULL
);

CREATE FUNCTION log_customer_city_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO customer_city_changes (
        customer_id, old_city, new_city, changed_at
    )
    VALUES (OLD.customer_id, OLD.city, NEW.city, now());
    RETURN NULL;
END;
$$;

CREATE TRIGGER customers_city_history
AFTER UPDATE OF city ON customers
FOR EACH ROW
EXECUTE FUNCTION log_customer_city_change();

UPDATE customers SET city = '부산' WHERE customer_id = 1;

SELECT change_id, customer_id, old_city, new_city FROM customer_city_changes;
