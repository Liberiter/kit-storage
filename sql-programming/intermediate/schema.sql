-- world: 온라인 서점 "책숲"의 운영 데이터 — 이 코스의 모든 챕터가 공유하는 world.
--
-- 핵심 다섯 테이블(customers·books·orders·order_items·reviews)은 앞 코스(fundamentals)의
-- 책숲과 열·타입·제약·데이터가 같다. 달라진 것은 하나 — books.category 가 분류 트리
-- (categories.name)를 가리키는 외래키를 얻었다. 그 위에 운영 테이블 일곱을 더했다:
--   categories      분류 트리 (자기 참조 — 재귀 질의 대상)
--   staff           직원·상사 (자기 참조 — self join 대상)
--   book_meta       ISBN·태그 배열
--   book_supply     공급 현황 (외부 피드로 갱신하는 UPSERT 대상)
--   supplier_feed   공급사 피드 원본 (중복·오류 행 포함, 제약 최소)
--   stock_movements 재고 입출고 원장 (시계열·누적 합 대상; 합계 = books.stock)
--   page_views      도서 페이지 조회 로그 (약 20만 행 — 실행 계획·시간대·JSONB 대상)
--
-- 적재 차례(reset.sh): schema.sql → seed_ref.sql(분류·직원) → seed.sql(핵심 다섯 테이블,
-- 생성기 generate_seed.py) → seed_ops.sql(운영 테이블 — 적재 시 결정적으로 생성) →
-- legacy.sql(스키마 legacy) → antipatterns.sql(스키마 antipatterns).
--
-- page_views 와 stock_movements 에는 기본 키 말고 인덱스를 두지 않았다. 인덱스를
-- 만들기 전후의 실행 계획을 비교하는 것이 11장의 내용이다.

-- ---------- 분류 트리 (books 보다 먼저 — books.category 가 참조한다) ----------
CREATE TABLE categories (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text    NOT NULL UNIQUE,
    parent_id   integer REFERENCES categories (category_id)   -- 최상위 분류는 NULL
);

-- ---------- 핵심 다섯 테이블 (앞 코스와 같은 정의) ----------
CREATE TABLE customers (
    customer_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text    NOT NULL,
    email            text    NOT NULL UNIQUE,
    city             text    NOT NULL,
    signup_date      date    NOT NULL,
    marketing_opt_in boolean NOT NULL,
    birth_date       date                -- 선택 입력: NULL 허용
);

CREATE TABLE books (
    book_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          text    NOT NULL,
    author         text    NOT NULL,
    category       text    NOT NULL REFERENCES categories (name),   -- 분류 이름(자연 키) 참조
    price          integer NOT NULL CHECK (price > 0),
    page_count     integer NOT NULL CHECK (page_count > 0),
    published_date date    NOT NULL,
    stock          integer NOT NULL CHECK (stock >= 0)
);

CREATE TABLE orders (
    order_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer NOT NULL REFERENCES customers (customer_id),
    order_date   date    NOT NULL,
    status       text    NOT NULL
                 CHECK (status IN ('배송준비', '배송중', '배송완료', '취소')),
    shipped_date date,               -- 아직 발송 전이면 NULL
    -- 발송된 상태(배송중·배송완료)일 때만 발송일이 있다 (world 정합성)
    CHECK ((status IN ('배송중', '배송완료')) = (shipped_date IS NOT NULL)),
    CHECK (shipped_date IS NULL OR shipped_date >= order_date)
);

CREATE TABLE order_items (
    order_id   integer NOT NULL REFERENCES orders (order_id),
    book_id    integer NOT NULL REFERENCES books (book_id),
    quantity   integer NOT NULL CHECK (quantity > 0),
    unit_price integer NOT NULL CHECK (unit_price > 0),  -- 주문 시점 단가
    PRIMARY KEY (order_id, book_id)
);

CREATE TABLE reviews (
    review_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     integer NOT NULL REFERENCES books (book_id),
    customer_id integer NOT NULL REFERENCES customers (customer_id),
    order_id    integer REFERENCES orders (order_id),
                -- 구매 인증 리뷰면 해당 주문, 아니면 NULL — NULL 허용 외래키
    rating      integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment     text,                -- 별점만 남긴 리뷰는 NULL
    review_date date    NOT NULL,
    UNIQUE (book_id, customer_id)    -- 한 사람이 한 책에 리뷰 하나
);

-- ---------- 운영 테이블 ----------
CREATE TABLE staff (
    staff_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text    NOT NULL,
    department text    NOT NULL
               CHECK (department IN ('경영', '운영', '물류', '고객지원', '개발')),
    title      text    NOT NULL CHECK (title IN ('대표', '팀장', '매니저', '사원')),
    manager_id integer REFERENCES staff (staff_id),   -- 대표는 NULL (자기 참조)
    hired_date date    NOT NULL
);

CREATE TABLE book_meta (
    book_id integer PRIMARY KEY REFERENCES books (book_id),
    isbn13  text    NOT NULL UNIQUE
            CHECK (isbn13 ~ '^979-11-[0-9]{5}-[0-9]{3}-[0-9]$'),
    tags    text[]  NOT NULL CHECK (cardinality(tags) >= 1)   -- 배열 열
);

CREATE TABLE book_supply (
    -- 공급사가 알려 준 공급가·공급 가능 재고의 최신 상태. supplier_feed 를 반복
    -- 적재하며 갱신한다 (UPSERT 대상 — 행이 없으면 넣고, 있으면 고친다).
    book_id        integer     PRIMARY KEY REFERENCES books (book_id),
    supplier_price integer     NOT NULL CHECK (supplier_price > 0),
    supplier_stock integer     NOT NULL CHECK (supplier_stock >= 0),
    updated_at     timestamptz NOT NULL
);

CREATE TABLE supplier_feed (
    -- 공급사가 보낸 피드를 **받은 그대로** 쌓는 테이블. 외래키도 CHECK 도 두지 않았다
    -- — 같은 책이 날짜를 달리해 반복 등장하고, 똑같은 행이 두 번 들어 있고, 없는
    -- 책 번호와 음수 가격도 섞여 있다. 이 원본을 book_supply 로 옮기는 것이 실습이다.
    feed_id        integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_date      date        NOT NULL,
    book_id        integer     NOT NULL,
    supplier_price integer     NOT NULL,
    supplier_stock integer     NOT NULL,
    received_at    timestamptz NOT NULL
);

CREATE TABLE stock_movements (
    -- 재고 입출고 원장. 책마다 quantity 의 합이 books.stock 과 같다 (world 정합성).
    movement_id integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     integer     NOT NULL REFERENCES books (book_id),
    moved_at    timestamptz NOT NULL,
    quantity    integer     NOT NULL CHECK (quantity <> 0),   -- 입고 +, 출고 −
    reason      text        NOT NULL CHECK (reason IN ('입고', '출고', '반품', '조정')),
    order_id    integer     REFERENCES orders (order_id),     -- 출고면 해당 주문, 아니면 NULL
    staff_id    integer     NOT NULL REFERENCES staff (staff_id)
);

CREATE TABLE page_views (
    -- 도서 상세 페이지 조회 로그 (2026-06-01 ~ 2026-08-31, 약 20만 행).
    view_id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viewed_at   timestamptz NOT NULL,                       -- 절대 시각 (UTC 로 저장)
    book_id     integer     NOT NULL REFERENCES books (book_id),
    customer_id integer     REFERENCES customers (customer_id),   -- 로그인하지 않은 방문은 NULL
    client_tz   text        NOT NULL,                       -- 방문자의 시간대 이름 (Asia/Seoul 등)
    context     jsonb       NOT NULL
                -- {"device": …, "referrer": …, "dwell_ms": 정수, "scroll_pct": 정수, ("utm": …)}
);
-- 통계 표본을 전체 행으로 고정한다: ANALYZE 는 기본값으로 3만 행을 무작위 표본으로 읽어
-- 실행 계획의 추정 행 수·비용이 구축마다 조금씩 달라진다. 한 열의 통계 목표를 10000 으로
-- 올리면 표본 크기(300×10000)가 전체 행 수를 넘어 ANALYZE 가 테이블을 통째로 읽고, 그래서
-- 언제 누가 ANALYZE 를 돌려도 같은 통계가 나온다 — 책마다의 조회 수가 정확히 잡힌다.
ALTER TABLE page_views ALTER COLUMN book_id SET STATISTICS 10000;
